"""Turning an ``EvalReport`` into something a person reads.

Separate from ``runner.py`` because formatting is where the temptation to
flatter the numbers lives, and it should be nowhere near the code that computes
them. Nothing here rounds, filters or reorders in a way that changes what the
table says: the ablation is printed in a fixed mode order, and a mode that lost
is printed exactly as it lost.
"""

from __future__ import annotations

from app.evaluation.dataset import EvalDataset
from app.evaluation.runner import EvalReport, ModeName


def ablation_table(report: EvalReport, *, markdown: bool = False) -> str:
    """The four-row comparison: one row per retrieval mode."""
    header = ["Method", "Recall@5", "Recall@10", "MRR", "nDCG@10", "ms/query"]
    rows = [
        [
            s.label,
            f"{s.recall_at_5:.3f}",
            f"{s.recall_at_10:.3f}",
            f"{s.mrr:.3f}",
            f"{s.ndcg:.3f}",
            f"{s.mean_ms:.1f}",
        ]
        for s in report.summaries
    ]
    if markdown:
        lines = ["| " + " | ".join(header) + " |"]
        lines.append("|" + "|".join(["---"] * len(header)) + "|")
        lines += ["| " + " | ".join(row) + " |" for row in rows]
        return "\n".join(lines)

    widths = [max(len(header[i]), *(len(r[i]) for r in rows)) for i in range(len(header))]
    out = ["  ".join(h.ljust(widths[i]) for i, h in enumerate(header))]
    out.append("  ".join("-" * w for w in widths))
    out += ["  ".join(r[i].ljust(widths[i]) for i in range(len(header))) for r in rows]
    return "\n".join(out)


def per_query_table(report: EvalReport, dataset: EvalDataset) -> str:
    """Where the first relevant question landed, per query, per mode.

    The aggregate table says *whether* something improved; this says *which
    queries* moved, which is the only way to tell a real effect from one lucky
    query in a set this small. ``-`` means nothing relevant was retrieved at all.
    """
    modes: list[ModeName] = [s.mode for s in report.summaries]
    header = f"{'query':<8} {'kind':<9} " + " ".join(f"{m[:9]:>9}" for m in modes) + "  relevant"
    lines = [header, "-" * (len(header) + 20)]
    for query in dataset:
        outcomes = report.outcomes_for(query.id)
        cells = []
        for mode in modes:
            outcome = outcomes.get(mode)
            cells.append("?" if outcome is None else _rank_cell(outcome.first_rank))
        expected = ",".join(sorted(query.primary_ids)) or ",".join(sorted(query.relevant_ids))
        lines.append(
            f"{query.id:<8} {query.kind:<9} " + " ".join(f"{c:>9}" for c in cells) + f"  {expected}"
        )
    return "\n".join(lines)


def _rank_cell(rank: int | None) -> str:
    return "-" if rank is None else str(rank)


def by_kind_table(report: EvalReport, dataset: EvalDataset) -> str:
    """MRR broken down by the retrieval situation each query was written to test.

    An average over mixed cases hides exactly what an ablation is for: a
    reranker can lift the semantic queries and hurt the lexical ones and show
    no change at all in the headline number.
    """
    modes: list[ModeName] = [s.mode for s in report.summaries]
    kinds = sorted(dataset.by_kind())
    header = f"{'kind':<10} {'n':>3}  " + " ".join(f"{m[:9]:>9}" for m in modes)
    lines = [header, "-" * len(header)]
    for kind in kinds:
        ids = {q.id for q in dataset.by_kind()[kind]}
        cells = []
        for mode in modes:
            rows = [o for o in report.outcomes if o.mode == mode and o.query_id in ids]
            cells.append(f"{sum(o.reciprocal_rank for o in rows) / len(rows):.3f}" if rows else "-")
        lines.append(f"{kind:<10} {len(ids):>3}  " + " ".join(f"{c:>9}" for c in cells))
    return "\n".join(lines)


def config_block(report: EvalReport) -> str:
    """Everything needed to reproduce the run, printed above the numbers."""
    c = report.config
    kind = "REAL models" if c.real_models else "DETERMINISTIC stand-ins (not a quality measurement)"
    return "\n".join(
        [
            f"dataset      : {c.dataset_path}",
            f"questions    : {c.question_count} in the bank",
            f"models       : {kind}",
            f"  embedder   : {c.embedder_model}",
            f"  reranker   : {c.reranker_model or '(none)'}",
            f"depth        : top {c.depth} scored per mode",
            f"K values     : vector_k={c.vector_k} lexical_k={c.lexical_k} "
            f"candidate_k={c.candidate_k} rrf_k={c.rrf_k:g}",
        ]
    )


def markdown_report(report: EvalReport, dataset: EvalDataset) -> str:
    """The committed artefact written to ``evals/reports/``."""
    c = report.config
    parts = [
        "# Retrieval evaluation — Phase 2 Day 10",
        "",
        "Generated by `python scripts/run_retrieval_eval.py --write-report`.",
        "Regenerating with the same dataset, bank and models reproduces it exactly.",
        "",
        "## Configuration",
        "",
        "```",
        config_block(report),
        "```",
        "",
        "## Ablation",
        "",
        ablation_table(report, markdown=True),
        "",
        f"{len(dataset)} queries, each scored over the top {c.depth} results. "
        "Recall@5 is the first five of that same list, not a second run.",
        "",
        "## MRR by query kind",
        "",
        "```",
        by_kind_table(report, dataset),
        "```",
        "",
        "## Per query — rank of the first relevant question",
        "",
        "```",
        per_query_table(report, dataset),
        "```",
        "",
        "## Misses",
        "",
    ]
    any_miss = False
    for summary in report.summaries:
        if summary.misses:
            any_miss = True
            parts.append(f"- **{summary.label}**: {', '.join(summary.misses)}")
    if not any_miss:
        parts.append("None: every mode retrieved something relevant for every query.")
    parts.append("")
    return "\n".join(parts)


