"""The provisional reference labels' quality report - Day 19, Part 2.3.

    python scripts/report_reference_labels.py            # print and write the report

Pure analysis: reads ``reference_labels.jsonl`` and ``answers.jsonl``, makes no
model calls, and writes ``evals/reports/reference_labels.md``.

**What this report is for.** The labels are the yardstick everything else in
Day 19 is measured against, so the first question is not "what is the QWK" but
"is this yardstick any good". The answer, on the evidence below, is *partly*:
it is better isolated than either Day-18 pass and worse distributed than both,
and it shares a model with the grader it is used to measure. All three facts are
in here rather than in a footnote.
"""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from app.grading.evalset import QUALITY_LEVELS, load_answers  # noqa: E402
from app.grading.reflabel import (  # noqa: E402
    REFERENCE_RUBRIC_VERSION,
    by_intent,
    central_tendency,
    labels_by_answer,
    load_reference_labels,
    needs_adjudication,
    reference_label_problems,
    score_distribution,
    uncertain_rows,
)
from app.grading.validity import agreement  # noqa: E402

DATASET_DIR = BACKEND.parent / "evals" / "datasets" / "grading"
ANSWERS_PATH = DATASET_DIR / "answers.jsonl"
LABELS_PATH = DATASET_DIR / "reference_labels.jsonl"
REPORT_PATH = BACKEND.parent / "evals" / "reports" / "reference_labels.md"

#: Rows the Day-18 dataset README disclosed before its second pass ran, and
#: which that pass is therefore contaminated on. Carried forward here because
#: the contamination is a property of *those labels*, not of this analysis, and
#: any comparison against pass A has to be able to exclude them.
DAY18_DISCLOSED = (
    "eval-0070",
    "eval-0025",
    "eval-0085",
    "eval-0105",
    "eval-0018",
    "eval-0019",
)


def main() -> int:
    if not LABELS_PATH.exists():
        print(f"no reference labels at {LABELS_PATH}; run build_reference_labels.py first")
        return 1

    answers = load_answers(ANSWERS_PATH)
    labels = load_reference_labels(LABELS_PATH)
    blind = labels_by_answer(labels, pass_name="blind")
    aware = labels_by_answer(labels, pass_name="concept_aware")
    intents: dict[str, str] = {a.id: str(a.quality_intent) for a in answers}
    by_id = {a.id: a for a in answers}

    out: list[str] = []
    w = out.append

    w("# Provisional reference labels - quality report")
    w("")
    w("Generated by `backend/scripts/report_reference_labels.py`. No model calls.")
    w("")
    w("## What these labels are")
    w("")
    w("| | |")
    w("|---|---|")
    w(f"| Rows | **{len(blind)}** blind pass, **{len(aware)}** concept-aware pass |")
    w(f"| Rubric version | `{REFERENCE_RUBRIC_VERSION}` |")
    models = sorted({row.evaluator_model for row in labels})
    w(f"| Evaluator | {', '.join(f'`{m}`' for m in models)} |")
    w(f"| Temperature | {sorted({row.temperature for row in labels})} |")
    w(
        '| Provenance | `label_source: "model"` on every row - **autonomous and '
        "model-generated**. No human annotated or verified any answer. |"
    )
    w("")
    w("> **These are not human labels and must never be reported as inter-rater")
    w("> reliability.** The Phase-4 QWK gate is written against human labels and")
    w("> remains unmet; `gate_eligible()` does not look at this file.")
    w("")

    # ---- the independence problem -----------------------------------------
    generators = sorted({a.generator_model for a in answers if a.generator_model})
    w("## The independence problem, stated first because it bounds everything else")
    w("")
    w(f"- Answers were **generated** by: {', '.join(f'`{g}`' for g in generators)}")
    w(f"- Reference labels were **assigned** by: {', '.join(f'`{m}`' for m in models)}")
    w("")
    if set(generators) & set(models):
        w("**These are the same model.** The configured provider (`nvidia`) serves every")
        w("capability tier from one model, so the answer generator, the grader under test")
        w("and this reference labeller are all the same weights. A QWK computed between")
        w("the grader and these labels measures *agreement between two prompts to one")
        w("model*, not validity against an independent judgement, and a shared blind spot")
        w("is invisible to it.")
        w("")
        w("This is a limitation of the available infrastructure, not a design choice, and")
        w("it is the main reason the Day-18 label passes are retained and reported")
        w("alongside: those were produced by a *different* model family, so despite their")
        w("own contamination they are the less circular reference for grader validity.")
    else:
        w("The labeller and the generator are different models.")
    w("")

    # ---- distribution ------------------------------------------------------
    w("## Score distribution")
    w("")
    dist = score_distribution(list(blind.values()))
    tendency = central_tendency(list(blind.values()))
    w("| Band | 0 | 1 | 2 | 3 | 4 |")
    w("|---|--:|--:|--:|--:|--:|")
    w("| Count | " + " | ".join(str(dist[b]) for b in range(5)) + " |")
    w("")
    w(
        f"- modal band **{tendency['modal_band']}**, holding "
        f"**{tendency['modal_share']:.1%}** of all rows"
    )
    w(
        f"- populated bands: **{tendency['populated_bands']}/5**, "
        f"effective range **{tendency['effective_range']}**"
    )
    w("")
    modal_share = tendency["modal_share"]
    assert isinstance(modal_share, float)
    if modal_share > 0.5:
        w("**This is severe central tendency and it is the biggest weakness of this")
        w("pass.** More than half the dataset sits in one band, so the labels carry very")
        w("little information about the *ordering* of those rows. A quadratically")
        w("weighted kappa needs disagreement in the reference marginal to have anything")
        w("to divide by; with a marginal this concentrated the statistic is close to")
        w("degenerate and will read low **regardless of how good the grader is**.")
        w("")
        w("It is reported rather than corrected. Re-binning, rescaling or re-prompting")
        w("the labeller until the histogram looked better would be fitting the yardstick")
        w("to the thing it measures.")
        w("")

    # ---- by construction intent -------------------------------------------
    w("## Mean label by construction intent")
    w("")
    w("A **diagnostic, not a target.** `quality_intent` is the instruction the")
    w("generator was given; Day 18 established it is unreliable (19 of 24")
    w("`wrong_confident` answers contain no error). No label was adjusted toward its")
    w("intent.")
    w("")
    report = by_intent(list(blind.values()), intents)
    w("| Intent | n | mean | median | min | max | 0 | 1 | 2 | 3 | 4 |")
    w("|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for level in QUALITY_LEVELS:
        row = report.get(level)
        if not row:
            continue
        d = row["distribution"]
        assert isinstance(d, dict)
        w(
            f"| `{level}` | {row['n']} | {row['mean']:.2f} | {row['median']} "
            f"| {row['min']} | {row['max']} | " + " | ".join(str(d[b]) for b in range(5)) + " |"
        )
    means = [
        value
        for lv in QUALITY_LEVELS
        if lv in report and isinstance(value := report[lv]["mean"], float)
    ]
    descending = means == sorted(means, reverse=True)
    w("")
    w(
        f"- means descend in the designed order: **{descending}** "
        f"(spread {max(means) - min(means):.2f})"
        if means
        else "- no intents matched"
    )
    w("")

    # ---- correctness and evidence fields ----------------------------------
    w("## What the labeller said it saw")
    w("")
    correctness = Counter(row.judgment.correctness for row in blind.values())
    w("| Correctness assessment | n |")
    w("|---|--:|")
    for key, count in correctness.most_common():
        w(f"| `{key}` | {count} |")
    w("")
    with_errors = [r for r in blind.values() if r.judgment.factual_errors]
    with_omissions = [r for r in blind.values() if r.judgment.omissions]
    with_unsupported = [r for r in blind.values() if r.judgment.unsupported_claims]
    w(
        f"- rows where at least one **factual error** was identified: "
        f"**{len(with_errors)}/{len(blind)}**"
    )
    w(
        f"- rows where at least one **omission** was identified: "
        f"**{len(with_omissions)}/{len(blind)}**"
    )
    w(
        f"- rows with at least one **unsupported claim**: "
        f"**{len(with_unsupported)}/{len(blind)}**"
    )
    w("")
    w("The gap between those first two numbers is itself a finding: this labeller")
    w("readily identifies *missing* content and rarely identifies *wrong* content,")
    w("which is consistent with the Day-18 observation that the generator writes")
    w("fluent, mostly-correct prose - and also consistent with a labeller that is")
    w("reluctant to call its own model family wrong. The two cannot be separated with")
    w("the evidence available here.")
    w("")

    # ---- uncertainty -------------------------------------------------------
    unsure = uncertain_rows(list(blind.values()), below=0.7)
    w("## Rows the labeller was least sure of")
    w("")
    if unsure:
        w("| answer | confidence | score | intent |")
        w("|---|--:|--:|---|")
        for answer_id, confidence, score in unsure[:15]:
            w(f"| {answer_id} | {confidence:.2f} | {score} | `{intents[answer_id]}` |")
        w("")
        w(f"{len(unsure)} rows below 0.70 confidence. These are the rows to check by hand")
        w("first; an aggregate that treats them like a 0.95-confidence row overstates")
        w("its own precision.")
    else:
        w("No row was labelled with confidence below 0.70.")
    w("")

    # ---- cross-pass agreement ---------------------------------------------
    w("## Agreement with the two Day-18 passes")
    w("")
    w("All three passes are model-generated. None of these numbers is inter-rater")
    w("reliability in the human sense, and none of them validates any pass.")
    w("")
    w("| Comparison | n | QWK | Spearman | MAE | exact | within 1 |")
    w("|---|--:|--:|--:|--:|--:|--:|")

    comparisons: list[tuple[str, list[int], list[int]]] = []
    ids = sorted(blind)
    comparisons.append(
        (
            "Day-19 blind vs Day-18 pass A",
            [pass_a for i in ids if (pass_a := by_id[i].human_score) is not None],
            [blind[i].score for i in ids if by_id[i].human_score is not None],
        )
    )
    comparisons.append(
        (
            "Day-19 blind vs Day-18 retired",
            [retired for i in ids if (retired := by_id[i].model_score) is not None],
            [blind[i].score for i in ids if by_id[i].model_score is not None],
        )
    )
    clean = [i for i in ids if i not in DAY18_DISCLOSED and by_id[i].human_score is not None]
    comparisons.append(
        (
            "Day-19 blind vs Day-18 pass A (excl. 6 disclosed rows)",
            [pass_a_clean for i in clean if (pass_a_clean := by_id[i].human_score) is not None],
            [blind[i].score for i in clean],
        )
    )
    if aware:
        both = sorted(set(blind) & set(aware))
        comparisons.append(
            (
                "Day-19 blind vs Day-19 concept-aware",
                [blind[i].score for i in both],
                [aware[i].score for i in both],
            )
        )

    for label_text, left, right in comparisons:
        if len(left) < 2:
            continue
        rep = agreement(left, right, label=label_text)
        w(
            f"| {label_text} | {rep.n} | {rep.qwk:+.4f} | {rep.spearman:+.4f} | {rep.mae:.3f} "
            f"| {rep.exact_rate:.1%} | {rep.adjacent_rate:.1%} |"
        )
    w("")

    if aware:
        contested = needs_adjudication(blind, aware)
        w(
            f"- rows where the two Day-19 passes differ by two bands or more: "
            f"**{len(contested)}**"
        )
        if contested:
            w(f"  - {', '.join(contested)}")
        adjudicated = [r for r in blind.values() if r.adjudication is not None]
        if adjudicated:
            revised = [r for r in adjudicated if r.adjudication == "revised"]
            w(
                f"- adjudicated: **{len(adjudicated)}**, of which the adjudicator revised "
                f"the blind score on **{len(revised)}**"
            )
        w("")
    else:
        w("- the concept-aware second pass was **not run**; see the Day-19 report for why.")
        w("")

    # ---- caution list ------------------------------------------------------
    w("## Rows requiring caution, and why")
    w("")
    w("| Row | Reason |")
    w("|---|---|")
    leaked = [a.id for a in answers if "not supposed to go into that" in a.answer]
    for answer_id in leaked:
        w(f"| {answer_id} | contains a leaked generation instruction in the answer text |")
    for answer_id in DAY18_DISCLOSED:
        w(f"| {answer_id} | disclosed in the Day-18 README; **pass A is contaminated** on it |")
    for answer_id, confidence, _ in unsure[:5]:
        w(f"| {answer_id} | labeller confidence {confidence:.2f} |")
    w("")
    w("No row was excluded from the aggregate statistics. Exclusions are reported as")
    w("separate columns (see the 'excl. 6 disclosed rows' line above) rather than")
    w("applied silently, so that every number can be traced to the rows it covers.")
    w("")

    # ---- validation --------------------------------------------------------
    problems = reference_label_problems(
        labels, expected_answers=[a.id for a in answers], pass_name="blind"
    )
    w("## Validation")
    w("")
    if problems:
        for problem in problems:
            w(f"- **PROBLEM** {problem}")
    else:
        w("- all 120 answers have exactly one blind label")
        w("- every score is an integer in 0-4")
        w("- no duplicate answer ids, no labels for unknown answers")
        w("- every question id matches the dataset")
        w(f"- every row carries rubric version `{REFERENCE_RUBRIC_VERSION}` and full provenance")
        w("- no row recorded a retry failure")
    w("")

    text = "\n".join(out) + "\n"
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(text, encoding="utf-8")
    print(text)
    print(f"  wrote {REPORT_PATH}")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
